import test from "node:test";
import assert from "node:assert/strict";
import {randomUUID} from "node:crypto";
import {db} from "../lib/server/db";
import {sourceTextHash} from "../lib/regulatory/source-fingerprint.mjs";
import {hashValue,type Analysis} from "../lib/regulatory/intelligence";
import {createIntelligenceRun,decideCandidate,getIntelligenceWorkspace,saveBusinessProfile} from "../lib/server/intelligence-service";
import type {AuthorizedContext} from "../lib/server/authorization";

test("intelligence workflow: isolation, review gates, exactly-once tasks, stale context and integrity",async()=>{
  const suffix=randomUUID();
  const users=await Promise.all(["maker","reviewer","outside"].map(n=>db.user.create({data:{externalId:n+suffix,email:n+suffix+"@example.invalid"}})));
  const orgs=await Promise.all(["A","B"].map(n=>db.organization.create({data:{name:"Fictional intelligence "+n+suffix}})));
  const ctx=(u:number,o:number,role:AuthorizedContext["role"]):AuthorizedContext=>({userId:users[u].id,organizationId:orgs[o].id,role});
  const maker=ctx(0,0,"OWNER"),reviewer=ctx(1,0,"ADMIN"),outside=ctx(2,1,"OWNER"),viewer=ctx(0,0,"VIEWER");
  const text="Businesses must retain supplier assessment records and keep them current. Staff should receive documented training before handling controlled drugs. You must not allow unauthorised access to secure areas.";
  const profile={activities:["controlled-drugs"],jurisdictions:["Scotland"]};
  const orgIds=orgs.map(o=>o.id);
  try{
    await db.membership.createMany({data:[maker,reviewer,outside].map(c=>({userId:c.userId,organizationId:c.organizationId,role:c.role}))});
    await assert.rejects(()=>saveBusinessProfile(viewer,profile,0),(e:any)=>e.status===403);
    await saveBusinessProfile(maker,profile,0);
    await assert.rejects(()=>saveBusinessProfile(reviewer,profile,0),(e:any)=>e.status===409);
    const snapshot=await db.regulatorySnapshot.create({data:{organizationId:maker.organizationId,sourceId:"home-office-domestic",title:"Fictional test source",url:"https://www.gov.uk/guidance/controlled-drugs-domestic-licences",bodyText:text,contentHash:sourceTextHash(text),capturedById:maker.userId}});
    await assert.rejects(()=>createIntelligenceRun(outside,snapshot.id),(e:any)=>e.status===404);
    await assert.rejects(()=>createIntelligenceRun(viewer,snapshot.id),(e:any)=>e.status===403);
    const generated=await createIntelligenceRun(maker,snapshot.id);
    assert.equal((await createIntelligenceRun(maker,snapshot.id)).id,generated.id);
    assert.equal((await getIntelligenceWorkspace(outside)).runs.length,0);
    const workspace=await getIntelligenceWorkspace(reviewer);
    assert.equal(workspace.runs[0].integrityValid,true,"JSONB must not break the canonical hash");
    const result=workspace.runs[0].result as unknown as Analysis;
    const accept={candidateKey:result.candidates[0].key,decision:"ACCEPTED",rationale:"Reviewed fictional applicability, conditions and evidence needed for this task.",title:"Check supplier records",ownerName:"Fictional QA lead",dueDate:"2027-01-31"};
    await assert.rejects(()=>decideCandidate(outside,generated.id,accept),(e:any)=>e.status===404);
    await assert.rejects(()=>decideCandidate(maker,generated.id,accept),(e:any)=>e.status===403);
    await assert.rejects(()=>decideCandidate(reviewer,generated.id,accept),(e:any)=>e.status===409&&/source review/.test(e.message));
    await db.regulatorySnapshot.update({where:{id:snapshot.id},data:{reviewStatus:"REVIEWED",reviewerId:reviewer.userId,reviewedAt:new Date()}});
    await assert.rejects(()=>decideCandidate(reviewer,generated.id,{...accept,dueDate:"2027-02-31"}),(e:any)=>e.status===400);
    const outcomes=await Promise.allSettled([decideCandidate(reviewer,generated.id,accept),decideCandidate(reviewer,generated.id,accept)]);
    assert.equal(outcomes.filter(r=>r.status==="fulfilled").length,1);
    assert.equal(await db.obligation.count({where:{organizationId:maker.organizationId,originKey:accept.candidateKey}}),1);
    const accepted=(await getIntelligenceWorkspace(reviewer)).runs[0].decisions[0];
    assert.equal(accepted.obligation?.evidence.state,"missing-evidence");
    assert.equal(accepted.obligation?.status,"OPEN");
    const next={...accept,candidateKey:result.candidates[1].key};
    await db.regulatorySnapshot.update({where:{id:snapshot.id},data:{lastCheckedAt:new Date(Date.now()-8*86400000)}});
    await assert.rejects(()=>decideCandidate(reviewer,generated.id,next),(e:any)=>e.status===409&&/seven days/.test(e.message));
    await db.regulatorySnapshot.update({where:{id:snapshot.id},data:{lastCheckedAt:new Date()}});
    await saveBusinessProfile(reviewer,profile,1);
    assert.equal((await getIntelligenceWorkspace(reviewer)).runs[0].stale,true);
    await assert.rejects(()=>decideCandidate(reviewer,generated.id,next),(e:any)=>e.status===409&&/profile changed/.test(e.message));
    const fresh=await createIntelligenceRun(maker,snapshot.id);
    await assert.rejects(()=>decideCandidate(reviewer,fresh.id,accept),(e:any)=>e.status===409&&/already has a task/.test(e.message));
    const dismissed=await decideCandidate(reviewer,fresh.id,{...next,decision:"DISMISSED"});
    assert.equal(dismissed.obligationId,null);
    await db.intelligenceRun.update({where:{id:fresh.id},data:{result:{...result,candidates:[]}}});
    await assert.rejects(()=>decideCandidate(reviewer,fresh.id,{...accept,candidateKey:result.candidates[2].key}),(e:any)=>e.status===409&&/integrity/.test(e.message));
    assert.equal((await getIntelligenceWorkspace(reviewer)).runs[0].result,null);
    await db.intelligenceRun.update({where:{id:fresh.id},data:{result:result as any,resultHash:hashValue(result)}});
    const newer=await db.regulatorySnapshot.create({data:{organizationId:maker.organizationId,sourceId:snapshot.sourceId,title:snapshot.title,url:snapshot.url,bodyText:text+" Review the latest source.",contentHash:sourceTextHash(text+" Review the latest source."),capturedById:maker.userId,firstCapturedAt:new Date(Date.now()+1000)}});
    await assert.rejects(()=>decideCandidate(reviewer,fresh.id,{...accept,candidateKey:result.candidates[2].key}),(e:any)=>e.status===409&&/Source or business profile/.test(e.message));
    await assert.rejects(()=>db.intelligenceRun.create({data:{organizationId:outside.organizationId,snapshotId:newer.id,profileVersion:1,profile,engineVersion:"test",result:{},resultHash:hashValue({}),createdById:outside.userId}}),"database foreign key must block cross-organisation snapshot links");
    const events=await db.auditEvent.findMany({where:{organizationId:maker.organizationId,action:"intelligence.candidate_accepted"}});
    assert.equal(events.length,1,"task, decision and audit must commit atomically");
  }finally{
    await db.intelligenceDecision.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.intelligenceRun.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.businessProfile.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.auditEvent.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.obligation.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.regulatorySnapshot.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.membership.deleteMany({where:{organizationId:{in:orgIds}}});
    await db.organization.deleteMany({where:{id:{in:orgIds}}});
    await db.user.deleteMany({where:{id:{in:users.map(u=>u.id)}}});
  }
});
