import test from "node:test";
import assert from "node:assert/strict";
import {db} from "../lib/server/db";
import {createPolicy,policyDetail,policyWorkspace,changePolicy,policyInbox,openAssignedPolicy,acknowledgePolicy} from "../lib/server/policy-service";
import {changeMember} from "../lib/server/team-service";
import {assuranceFixture,rejects,future} from "./helpers/assurance-fixture";
test("policy lifecycle binds independent publication, exact-version reading, tenant boundaries and revocation races",async()=>{
 const x=await assuranceFixture(),{o,ad,ed,st,la,out,staff,later,admin,editor,foreign,store}=x;
 const notes="Independently reviewed the complete fictional policy and its intended readership.";
 const publish=(version:number,revisionId:string,userIds:string[])=>({action:"PUBLISH",version,revisionId,revisionVersion:1,notes,userIds,dueDate:future(),confirm:true});
 try{
  const pending=await x.file(false),draft={title:"Fictional information security policy",summary:"Read the fictional access and information handling responsibilities.",evidenceId:pending.id};
  await assert.rejects(()=>createPolicy(o,draft),rejects(409));
  await assert.rejects(()=>createPolicy(st,draft),rejects(403));
  const file=await x.file();draft.evidenceId=file.id;
  await assert.rejects(()=>createPolicy(out,draft),rejects(409));
  const p=await createPolicy(o,draft),d=await policyDetail(o,p.id),r=d.revisions[0];
  await assert.rejects(()=>policyWorkspace(st),rejects(403));await assert.rejects(()=>policyDetail(out,p.id),rejects(404));
  await assert.rejects(()=>changePolicy(o,p.id,publish(1,r.id,[staff.id]),store),rejects(403));
  await assert.rejects(()=>changePolicy(ad,p.id,publish(1,r.id,[foreign.id]),store),rejects(409));
  await changePolicy(ad,p.id,publish(1,r.id,[staff.id,later.id]),store);
  let inbox=await policyInbox(st);assert.equal(inbox.length,1);assert.equal(inbox[0].number,1);
  const a=inbox[0],ack={version:a.version,fileHash:a.fileHash,readAndUnderstood:true};
  await assert.rejects(()=>acknowledgePolicy(st,a.id,ack),rejects(409),"must open exact version first");
  await assert.rejects(()=>openAssignedPolicy(la,a.id,store),rejects(404));
  await assert.rejects(()=>openAssignedPolicy(out,a.id,store),rejects(404));
  await openAssignedPolicy(st,a.id,store);
  await assert.rejects(()=>acknowledgePolicy(st,a.id,{...ack,fileHash:"a".repeat(64)}),rejects(409));
  const attempts=await Promise.allSettled([acknowledgePolicy(st,a.id,ack),acknowledgePolicy(st,a.id,ack)]);
  assert.equal(attempts.filter(r=>r.status==="fulfilled").length,1);
  const signed=await db.policyAssignment.findUniqueOrThrow({where:{id:a.id}});assert.equal(signed.acknowledgedHash,a.fileHash);
  await assert.rejects(()=>changePolicy(o,p.id,{action:"ASSIGN",version:1,userIds:[editor.id],dueDate:future()}),rejects(409));
  const added=await changePolicy(o,p.id,{action:"ASSIGN",version:2,userIds:[staff.id,editor.id],dueDate:future()});assert.equal("added" in added&&added.added,1);
  const late=(await policyInbox(la))[0];
  await assert.rejects(()=>openAssignedPolicy(la,late.id,{...store,async get(k){const bytes=await store.get(k);await changeMember(o,{action:"REMOVE",userId:later.id,expectedRole:"VIEWER"});return bytes;}}),rejects(403));
  assert.equal((await db.policyAssignment.findUniqueOrThrow({where:{id:late.id}})).status,"REVOKED");
  await db.membership.create({data:la});
  await assert.rejects(()=>changePolicy(o,p.id,{action:"ASSIGN",version:2,userIds:[later.id],dueDate:future()}),rejects(409));
  const second=await x.file();
  await changePolicy(o,p.id,{action:"REVISE",version:2,summary:"Version two updates the fictional access responsibilities.",evidenceId:second.id});
  const next=(await policyDetail(o,p.id)).revisions[0];
  assert.equal((await policyInbox(st))[0].number,1,"preparing a draft does not replace published reading");
  await changePolicy(ad,p.id,publish(3,next.id,[staff.id]),store);
  inbox=await policyInbox(st);assert.equal(inbox.length,1);assert.equal(inbox[0].number,2);assert.equal(inbox[0].status,"PENDING");
  assert.equal((await db.policyAssignment.findUniqueOrThrow({where:{id:a.id}})).status,"ACKNOWLEDGED");
  assert.equal((await policyDetail(o,p.id,r.id)).assignments.find(row=>row.id===a.id)?.acknowledgedHash,a.fileHash);
  await assert.rejects(()=>acknowledgePolicy(st,a.id,ack),rejects(404),"old version cannot accept another acknowledgement");
  const fresh=inbox[0];
  await assert.rejects(()=>openAssignedPolicy(st,fresh.id,{...store,async get(k){const bytes=await store.get(k);await db.evidence.update({where:{id:second.id},data:{scanStatus:"QUARANTINED"}});return bytes;}}),rejects(409));
  assert.equal((await policyInbox(st))[0].available,false);
  await db.evidence.update({where:{id:second.id},data:{scanStatus:"CLEAN"}});
  await assert.rejects(()=>openAssignedPolicy(st,fresh.id,{...store,async get(k){const bytes=await store.get(k);await changePolicy(o,p.id,{action:"WITHDRAW",version:4});return bytes;}}),rejects(404));
  assert.equal((await policyInbox(st)).length,0);
  assert.equal((await db.policyAssignment.findUniqueOrThrow({where:{id:a.id}})).acknowledgedHash,a.fileHash);
  await assert.rejects(()=>db.policyAssignment.create({data:{organizationId:x.b.id,revisionId:next.id,userId:foreign.id,dueDate:new Date()}}),"composite key blocks cross-tenant assignment");
  const other=await createPolicy(o,draft),otherRevision=(await policyDetail(o,other.id)).revisions[0];
  await assert.rejects(()=>changePolicy(ad,other.id,publish(1,otherRevision.id,[staff.id]),{...store,async get(k){const bytes=await store.get(k);await changeMember(o,{action:"ROLE",userId:admin.id,expectedRole:"ADMIN",role:"EDITOR"});return bytes;}}),rejects(403));
  assert.equal((await db.policy.findUniqueOrThrow({where:{id:other.id}})).currentRevision,0);
 }finally{await x.cleanup();}
});
