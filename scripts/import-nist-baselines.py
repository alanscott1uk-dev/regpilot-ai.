"""Reproduce the bundled SP 800-53B selection from the four NIST OSCAL profiles."""
import hashlib
import json
from pathlib import Path
import re
import sys
from urllib.request import urlopen

revision = "f0de6d8d8c059d374f15e0ae07508d82e370fc1d"
base = f"https://raw.githubusercontent.com/usnistgov/oscal-content/{revision}/nist.gov/SP800-53/rev5/json/"
prefix = "NIST_SP-800-53_rev5_"
cache = Path(sys.argv[1]) if len(sys.argv) == 2 else None

def source(key, suffix):
    data = (cache / key).read_bytes() if cache else urlopen(base + prefix + suffix, timeout=40).read(6_000_001)
    if len(data) > 6_000_000:
        raise ValueError("Unrecognised OSCAL size")
    return json.loads(data), hashlib.sha256(data).hexdigest()

catalog, _ = source("catalog.json", "catalog-min.json")
titles = {}
def visit(controls):
    for row in controls:
        titles[row["id"]] = row["title"]
        visit(row.get("controls", []))
for group in catalog["catalog"]["groups"]:
    visit(group["controls"])
profiles, selected = {}, set()
for name in ["LOW", "MODERATE", "HIGH", "PRIVACY"]:
    data, digest = source(name, name + "-baseline_profile-min.json")
    profile = data["profile"]
    included, = profile["imports"]
    rule, = included["include-controls"]
    ids = rule["with-ids"]
    if (profile["metadata"]["version"] != "5.2.0" or set(included) != {"href", "include-controls"}
        or set(rule) != {"with-ids"} or len(ids) != len(set(ids))
        or any(x not in titles or not re.fullmatch(r"[a-z]{2}-[1-9]\d*(?:\.[1-9]\d*)?", x) for x in ids)):
        raise ValueError("Unexpected OSCAL source or selection")
    profiles[name] = {"fingerprint": digest, "controls": " ".join(ids)}
    selected.update(ids)

def as_js(name, value):
    return "export const " + name + "=" + json.dumps(value, indent=1, ensure_ascii=False) + ";\n"
output = "// Generated by scripts/import-nist-baselines.py from the pinned NIST OSCAL sources.\n"
output += as_js("revision", revision) + as_js("profiles", profiles)
output += as_js("controlTitles", {k: titles[k] for k in sorted(selected)})
Path("lib/nist-baseline-data.mjs").write_text(output)
