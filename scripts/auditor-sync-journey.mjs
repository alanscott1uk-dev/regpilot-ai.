import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

export async function auditorSyncJourney({review,guest,app,org,db,evidenceId,email,checkpoint,passed}){
  await checkpoint('publish a scoped audit package and synchronise it through the firm API');
  const evidence=await db.evidence.findUniqueOrThrow({where:{id:evidenceId},select:{filename:true,sha256:true}});
  await review.goto(app+'/team/audits?organizationId='+org.id);
  const draft=review.locator('section').filter({has:review.getByRole('heading',{name:'Prepare a review room',exact:true})});
  const title='External firm evidence sync';
  await draft.getByLabel('Room name',{exact:true}).fill(title);
  const today=new Date().toISOString().slice(0,10);
  await draft.getByLabel('Audit period starts').fill(today);
  await draft.getByLabel('Audit period ends').fill(today);
  await draft.getByLabel('What is this review for?').fill('Independently check the selected fictional training evidence through the audit firm interface.');
  await draft.getByLabel('Find a reviewed file').fill(evidence.filename);
  await draft.locator('input[type=checkbox][value="'+evidenceId+'"]').check();
  await draft.getByRole('button',{name:/Prepare draft/}).click();
  const detail=review.locator('section').filter({has:review.getByRole('heading',{name:title,exact:true})});
  await detail.getByRole('checkbox',{name:/I have checked the file contents/}).check();
  await detail.getByRole('button',{name:'Publish this selection'}).click();
  await detail.getByLabel('Verified pilot email').fill(email);
  await detail.getByRole('button',{name:'Create invitation'}).click();
  await detail.getByText(email,{exact:true}).waitFor();
  await guest.reload();
  const invite=guest.locator('article').filter({has:guest.getByRole('heading',{name:title,exact:true})});
  await invite.getByRole('button',{name:'Accept invitation'}).click();
  await guest.getByRole('button',{name:'Download file',exact:true}).waitFor();
  await review.reload();
  await review.getByRole('button',{name:new RegExp(title)}).click();
  await detail.getByText('Audit firm API access',{exact:true}).click();
  await detail.getByRole('button',{name:'Issue API key',exact:true}).click();
  const field=detail.getByLabel('One-time auditor key');
  await field.waitFor();
  const headers={authorization:'Bearer '+await field.inputValue()};
  await detail.getByRole('button',{name:'Hide key',exact:true}).click();
  const res=await fetch(app+'/api/v1/auditor/package',{headers});assert.equal(res.status,200);
  const pkg=await res.json();assert.deepEqual(pkg.evidence.map(item=>item.id),[evidenceId]);
  const file=await fetch(app+pkg.evidence[0].download,{headers});assert.equal(file.status,200);
  assert.equal(file.headers.get('content-digest'),'sha-256=:'+Buffer.from(evidence.sha256,'hex').toString('base64')+':');
  assert.equal(createHash('sha256').update(Buffer.from(await file.arrayBuffer())).digest('hex'),evidence.sha256);
  const conditional={...headers,'if-none-match':res.headers.get('etag')};
  assert.equal((await fetch(app+'/api/v1/auditor/package',{headers:conditional})).status,304);
  await detail.getByRole('button',{name:'Revoke API key',exact:true}).click();
  await detail.getByText('API key revoked.',{exact:true}).waitFor();
  assert.equal((await fetch(app+'/api/v1/auditor/package',{headers:conditional})).status,401);
  const member=await db.user.findUniqueOrThrow({where:{email},select:{id:true}});
  assert.equal(await db.membership.count({where:{organizationId:org.id,userId:member.id}}),0);
  passed('An external reviewer accepted a scoped invitation without joining the client workspace. Their firm key synchronised the package, verified the original bytes and ceased working on revocation.');
  return {files:1,verifiedSha256:true,conditionalStatus:304,revokedStatus:401,customerMemberships:0};
}
